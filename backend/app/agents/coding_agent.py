"""Coding agent that modifies and generates workspace source code."""

import logging
from typing import Any

from app.agents.state import AgentState
from app.core.security import validate_safe_relative_path
from app.integrations.nvidia_ai import NvidiaAIClient

logger = logging.getLogger(__name__)


class CodingAgent:
    """Produces code changes and test patches according to plan."""

    def __init__(self, ai_client: NvidiaAIClient) -> None:
        self.ai = ai_client

    async def execute_coding(
        self, state: AgentState, plan: dict[str, Any]
    ) -> dict[str, str]:
        """Generate code changes using AI or heuristic synthesis."""
        state.stage = "coding"
        state.progress = 45
        state.record_activity(
            "status",
            "coding",
            f"Synthesizing candidate code patches for {state.task_title}",
        )

        plan_summary = plan.get("summary", "")
        target_files = plan.get("target_files", [])
        context_files: dict[str, str] = {}
        for p in target_files:
            if p in state.initial_files:
                context_files[p] = state.initial_files[p]
        if not context_files:
            context_files = dict(state.initial_files)

        if self.ai.is_configured():
            try:
                state.record_activity(
                    "tool",
                    "coding",
                    f"Prompting Nebius Token Factory model ({self.ai.model}) to synthesize code changes.",
                    tool_name="nebius_nemotron_coder",
                )
                res = await self.ai.generate_code(
                    state.task_description, context_files, plan_summary
                )
                generated_files = res.get("files", {})
                if generated_files:
                    safe_generated = {}
                    for path, content in generated_files.items():
                        clean_path = validate_safe_relative_path(path)
                        safe_generated[clean_path] = content

                    state.current_files.update(safe_generated)
                    state.record_activity(
                        "message",
                        "coding",
                        f"Generated changes via Nebius Token Factory across {len(safe_generated)} file(s): {', '.join(safe_generated.keys())}",
                    )
                    return safe_generated
            except Exception as exc:
                logger.error("Nebius Token Factory code generation failed: %s. Failing closed without secondary provider fallback.", exc)
                state.record_activity(
                    "error",
                    "coding",
                    f"Nebius Token Factory code generation failed ({exc}). Failing closed without secondary AI provider fallback.",
                )
                raise

        # Fallback heuristic code patch
        modified: dict[str, str] = {}
        if not state.current_files:
            # Create a bootstrap implementation + test
            if state.language == "python":
                main_py = (
                    "# Generated by Kairo Coding Agent\n"
                    "def execute_task() -> dict:\n"
                    f"    '''{state.task_title}'''\n"
                    f"    return {{'task': '{state.task_title}', 'status': 'completed'}}\n"
                )
                test_py = (
                    "# Test generated by Kairo Coding Agent\n"
                    "from main import execute_task\n\n"
                    "def test_execute_task():\n"
                    "    res = execute_task()\n"
                    "    assert res['status'] == 'completed'\n"
                )
                state.current_files["main.py"] = main_py
                state.current_files["test_main.py"] = test_py
                modified["main.py"] = main_py
                modified["test_main.py"] = test_py
            else:
                index_js = (
                    "// Generated by Kairo Coding Agent\n"
                    f"export function executeTask() {{\n"
                    f"  return {{ task: '{state.task_title}', status: 'completed' }};\n"
                    f"}}\n"
                )
                test_js = (
                    "// Test generated by Kairo Coding Agent\n"
                    "import test from 'node:test';\n"
                    "import assert from 'node:assert';\n"
                    "import { executeTask } from './index.js';\n\n"
                    "test('executeTask returns completed', () => {\n"
                    "  const res = executeTask();\n"
                    "  assert.strictEqual(res.status, 'completed');\n"
                    "});\n"
                )
                state.current_files["index.js"] = index_js
                state.current_files["index.test.js"] = test_js
                modified["index.js"] = index_js
                modified["index.test.js"] = test_js
        else:
            # Modify existing file safely
            first_key = next(iter(state.current_files.keys()))
            orig_content = state.current_files[first_key]
            comment = f"\n# Kairo Agent update: {state.task_title}\n" if state.language == "python" else f"\n// Kairo Agent update: {state.task_title}\n"
            updated = orig_content + comment
            state.current_files[first_key] = updated
            modified[first_key] = updated

        state.record_activity(
            "message",
            "coding",
            f"Synthesized code updates for {len(modified)} file(s).",
        )
        return modified

